"""Build the Cloudflare version of Bugsay.

Renders every page with the real Flask app (so templates stay the single
source), copies static files, and exports the ferry data for the Worker.

    python cloudflare/build.py

Outputs (both git-ignored):
    cloudflare/public/           static site served by Workers Static Assets
    cloudflare/worker/generated/ data.js and page shells imported by the Worker
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PUBLIC = os.path.join(HERE, "public")
GENERATED = os.path.join(HERE, "worker", "generated")

try:
    import flask  # noqa: F401
except ImportError:  # wrangler runs this with whatever "python" is; prefer the project venv
    venv = os.path.join(ROOT, ".venv", "Scripts" if os.name == "nt" else "bin",
                        "python.exe" if os.name == "nt" else "python")
    if os.path.exists(venv) and os.path.abspath(sys.executable) != os.path.abspath(venv):
        sys.exit(subprocess.call([venv, __file__] + sys.argv[1:]))
    sys.exit("Flask isn't installed. Run: pip install -r requirements.txt")

sys.path.insert(0, ROOT)
import app as bugsay  # noqa: E402
import data  # noqa: E402

# URL -> file. Workers Static Assets serves /schedules from schedules.html.
PAGES = {
    "/": "index.html",
    "/schedules": "schedules.html",
    "/vehicle": "vehicle.html",
    "/availability": "availability.html",
    "/updates": "updates.html",
    "/faq": "faq.html",
    "/map": "map.html",
    "/tourism": "tourism.html",
    "/privacy": "privacy.html",
    "/my-trip": "my-trip.html",
}
MISSING_REF = "BG-ZZZZZZ"   # placeholder the Worker swaps for the code someone typed


def render(client, url, expect=200):
    resp = client.get(url)
    if resp.status_code != expect:
        raise SystemExit(f"{url} returned {resp.status_code}, expected {expect}")
    return resp.get_data(as_text=True)


def export_data():
    return {
        "trips": [data.serialize_trip(t) for t in data.TRIPS],
        "ports": data.PORTS,
        "routes": data.route_map(),
        "vehicleRoutes": data.route_map(vehicles_only=True),
        "passengerTypes": data.PASSENGER_TYPES,
        "paymentMethods": bugsay.PAYMENT_METHODS,
        "vehicleIcons": data.VEHICLE_ICONS,
        "statusLabels": data.STATUS_LABELS,
        "sailingStatus": [{"date": d, "trip_id": t, **entry}
                          for (d, t), entry in data.SAILING_STATUS.items()],
        "seatCapacity": data.SEAT_CAPACITY,
        "vehicleCapacity": data.VEHICLE_CAPACITY,
        "demoSeats": data.DEMO_SEATS_PER_CLASS,
        "demoSlots": data.DEMO_SLOTS_PER_VEHICLE_TYPE,
        "discountRate": data.DISCOUNT_RATE,
        "feeTicket": data.SERVICE_FEE_PER_TICKET,
        "feeVehicle": data.SERVICE_FEE_PER_VEHICLE,
        "maxPassengers": bugsay.MAX_PASSENGERS,
        "maxVehicles": bugsay.MAX_VEHICLES,
        "bookingWindowDays": bugsay.BOOKING_WINDOW_DAYS,
        "schema": bugsay.SCHEMA,
    }


def main():
    with tempfile.TemporaryDirectory() as tmp:
        app = bugsay.create_app({"TESTING": True, "DATABASE": os.path.join(tmp, "build.sqlite3")})
        client = app.test_client()

        shutil.rmtree(PUBLIC, ignore_errors=True)
        os.makedirs(PUBLIC)
        for url, name in PAGES.items():
            with open(os.path.join(PUBLIC, name), "w", encoding="utf-8", newline="\n") as fh:
                fh.write(render(client, url))
        with open(os.path.join(PUBLIC, "404.html"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(render(client, "/this-page-does-not-exist", 404))
        shutil.copytree(os.path.join(ROOT, "static"), os.path.join(PUBLIC, "static"))
        with open(os.path.join(PUBLIC, "_headers"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("/*\n  X-Content-Type-Options: nosniff\n"
                     "  Referrer-Policy: strict-origin-when-cross-origin\n  X-Frame-Options: SAMEORIGIN\n")

        # The Worker builds /booking/<ref> inside the My trip page, and reuses the
        # "not found" version of it for unknown references.
        shells = {
            "myTrip": render(client, "/my-trip"),
            "missing": render(client, "/booking/" + MISSING_REF, 404),
            "missingRef": MISSING_REF,
        }

    os.makedirs(GENERATED, exist_ok=True)
    with open(os.path.join(GENERATED, "data.js"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by cloudflare/build.py from data.py. Don't edit.\n")
        fh.write("export default " + json.dumps(export_data(), ensure_ascii=False, indent=1) + ";\n")
    with open(os.path.join(GENERATED, "shells.js"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by cloudflare/build.py from the Flask templates. Don't edit.\n")
        fh.write("export default " + json.dumps(shells, ensure_ascii=False) + ";\n")

    count = sum(len(files) for _, _, files in os.walk(PUBLIC))
    print(f"Built {len(PAGES) + 1} pages, {count} files in cloudflare/public, "
          "Worker data in worker/generated")


if __name__ == "__main__":
    main()
